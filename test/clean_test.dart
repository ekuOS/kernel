import 'dart:convert';
import 'dart:io';

import '../build.dart' as builder;

void check(bool value, String message) {
  if (!value) throw StateError(message);
}

Future<void> main() async {
  final temporary = await Directory.systemTemp.createTemp('ekuos-clean-test-');
  final script = Platform.script.resolve('../build.dart').toFilePath();
  var count = 0;

  Future<void> test(String name, Future<void> Function() body) async {
    await body();
    stdout.writeln('PASS $name');
    count++;
  }

  Future<Directory> fixture(String name, {bool legacy = false}) async {
    final root = await Directory('${temporary.path}/$name').create();
    final source = await Directory('${root.path}/linux').create();
    if (legacy) {
      await File('${source.path}/Makefile')
          .writeAsString('VERSION = 7\nPATCHLEVEL = 4\n');
      for (final path in ['arch/Kconfig', 'scripts/Kconfig.include']) {
        final file = File('${source.path}/$path');
        await file.parent.create(recursive: true);
        await file.writeAsString('# kernel fixture\n');
      }
    } else {
      await builder.markGenerated(source.path, 'source');
    }
    await File('${source.path}/local-change.c')
        .writeAsString('local source changes');
    for (final flavor in ['se', 'aa']) {
      final build = await Directory('${root.path}/build/linux-eku-$flavor')
          .create(recursive: true);
      final out = await Directory('${root.path}/out/linux-eku-$flavor')
          .create(recursive: true);
      if (!legacy) {
        await builder.markGenerated(build.path, 'build');
        await builder.markGenerated(out.path, 'artifacts');
      }
      await File('${build.path}/Makefile').writeAsString(
        '# Automatically generated by /linux/Makefile: Do not edit\n',
      );
      await Directory('${build.path}/certs').create();
      await File('${build.path}/certs/signing_key.pem')
          .writeAsString('private fixture key');
      await File('${out.path}/build-info.json').writeAsString(
        jsonEncode({
          'source': source.path,
          'makeVariables': <String, String>{},
          'files': <String>[],
        }),
      );
      await File('${out.path}/bzImage').writeAsString('kernel fixture');
    }
    await File('${root.path}/eku.conf').writeAsString('KEEP=y\n');
    await Directory('${root.path}/patches').create();
    await File('${root.path}/patches/keep.patch').writeAsString('keep patch');
    return root;
  }

  Future<ProcessResult> clean(Directory root, [List<String> args = const []]) =>
      Process.run(Platform.resolvedExecutable, [
        script,
        'clean',
        ...args,
        '--no-color',
      ], workingDirectory: root.path);

  void success(ProcessResult result) =>
      check(result.exitCode == 0, '${result.stdout}\n${result.stderr}');

  try {
    await test('clean options do not change build defaults', () async {
      check(
        builder.Options.parse([]).command == 'build',
        'Build default changed',
      );
      check(
        builder.Options.parse(['build']).command == 'build',
        'Explicit build rejected',
      );
      final options = builder.Options.parse([
        'clean',
        '--dry-run',
        '--keep-source',
      ]);
      check(
        options.command == 'clean' && options.dryRun && options.keepSource,
        'Missing clean flags',
      );
      for (final args in [
        ['--dry-run'],
        ['--keep-source'],
        ['clean', '--flavor', 'aa'],
      ]) {
        var rejected = false;
        try {
          builder.Options.parse(args);
        } on builder.BuildFailure {
          rejected = true;
        }
        check(rejected, 'Unexpectedly accepted $args');
      }
    });
    await test(
      'dry run reports all roots and preserves keys and source changes',
      () async {
        final root = await fixture('dry-run');
        final result = await clean(root, ['--dry-run']);
        success(result);
        check(
          'Would remove:'.allMatches(result.stdout.toString()).length == 3,
          'Wrong cleanup plan',
        );
        check(
          await File('${root.path}/linux/local-change.c').exists() &&
              await File(
                '${root.path}/build/linux-eku-aa/certs/signing_key.pem',
              ).exists() &&
              await File('${root.path}/out/linux-eku-se/bzImage').exists(),
          'Dry run deleted files',
        );
      },
    );
    await test(
      'clean removes generated trees and is repeatable, preserving inputs',
      () async {
        final root = await fixture('all');
        success(await clean(root));
        for (final name in ['out', 'build', 'linux']) {
          check(
            !await Directory('${root.path}/$name').exists(),
            '$name was not removed',
          );
        }
        check(
          await File('${root.path}/eku.conf').readAsString() == 'KEEP=y\n' &&
              await File('${root.path}/patches/keep.patch').exists(),
          'Cleanup removed inputs',
        );
        final again = await clean(root);
        success(again);
        check(
          'Already absent:'.allMatches(again.stdout.toString()).length == 3,
          'Missing roots failed',
        );
      },
    );
    await test('keep-source preserves the complete source tree', () async {
      final root = await fixture('keep-source');
      success(await clean(root, ['--keep-source']));
      check(
        await File('${root.path}/linux/local-change.c').exists() &&
            !await Directory('${root.path}/build').exists() &&
            !await Directory('${root.path}/out').exists(),
        'Incorrect keep-source behavior',
      );
    });
    await test(
      'legacy builds and source trees need no generated marker',
      () async {
        final root = await fixture('legacy', legacy: true);
        success(await clean(root));
        check(
          !await Directory('${root.path}/linux').exists() &&
              !await Directory('${root.path}/out').exists(),
          'Legacy roots were not cleaned',
        );
      },
    );
    await test('custom paths work outside the current directory', () async {
      final root = await fixture('custom-storage');
      final caller = await Directory('${temporary.path}/caller').create();
      success(
        await clean(caller, [
          '--source',
          '${root.path}/linux',
          '--output',
          '${root.path}/build',
          '--artifacts',
          '${root.path}/out',
        ]),
      );
      check(
        !await Directory('${root.path}/linux').exists() &&
            await caller.exists(),
        'Wrong custom paths deleted',
      );
    });
    await test('all targets are validated before the first deletion', () async {
      final root = await fixture('unknown-source');
      await File('${root.path}/linux/${builder.generatedMarker}').delete();
      final result = await clean(root);
      check(
        result.exitCode != 0 &&
            result.stderr.toString().contains('Unrecognized source'),
        'Unknown source was accepted',
      );
      check(
        await File('${root.path}/out/linux-eku-aa/bzImage').exists() &&
            await File('${root.path}/build/linux-eku-aa/certs/signing_key.pem')
                .exists() &&
            await File('${root.path}/linux/local-change.c').exists(),
        'Validation failure partially deleted targets',
      );
    });
    await test(
      'protected directories and configuration files cannot be deleted',
      () async {
        final root = await fixture('protected');
        await File('${root.path}/build/input.conf').writeAsString('keep');
        for (final args in [
          ['--source', '.'],
          ['--output', '..'],
          ['--artifacts', '/'],
          ['--artifacts', 'patches'],
          ['--config', 'build/input.conf'],
          ['--keep-source', '--output', 'linux'],
        ]) {
          final result = await clean(root, args);
          check(
            result.exitCode != 0 &&
                result.stderr.toString().contains('protected path'),
            'Protected path accepted: $args\n${result.stderr}',
          );
          check(
            await File('${root.path}/out/linux-eku-se/bzImage').exists(),
            'Protected-path failure deleted artifacts',
          );
        }
      },
    );
    await test(
      'symlink targets are refused, including trailing slash and dot aliases',
      () async {
        final root = await fixture('symlink-target');
        final outside = '${temporary.path}/outside-artifacts';
        await Directory('${root.path}/out').rename(outside);
        await Link('${root.path}/out').create(outside);
        for (final path in ['out', 'out/', 'out/.']) {
          final result = await clean(root, ['--artifacts', path]);
          check(
            result.exitCode != 0 &&
                result.stderr.toString().contains('symlink'),
            'Symlink target accepted: $path',
          );
          check(
            await File('$outside/linux-eku-se/bzImage').exists(),
            'Symlink target was followed',
          );
        }
      },
    );
    await test('recursive cleanup does not follow interior symlinks', () async {
      final root = await fixture('interior-link');
      final outside = await Directory('${temporary.path}/keep-outside')
          .create();
      await File('${outside.path}/keep.txt').writeAsString('keep');
      await Link('${root.path}/out/linux-eku-aa/external').create(outside.path);
      success(await clean(root));
      check(
        await File('${outside.path}/keep.txt').readAsString() == 'keep',
        'Interior symlink was followed',
      );
    });
    await test('nested build and source targets are removed once', () async {
      final root = await fixture('nested');
      await Directory('${root.path}/build').rename('${root.path}/linux/obj');
      final result = await clean(root, ['--output', 'linux/obj']);
      success(result);
      check(
        'Removing:'.allMatches(result.stdout.toString()).length == 2 &&
            !await Directory('${root.path}/linux').exists(),
        'Nested targets were not deduplicated',
      );
    });
    await test(
      'empty targets are removable but empty flavor children prove nothing',
      () async {
        final root = await Directory('${temporary.path}/empty').create();
        for (final name in ['linux', 'build', 'out']) {
          await Directory('${root.path}/$name').create();
        }
        success(await clean(root));
        await Directory('${root.path}/out/linux-eku-se')
            .create(recursive: true);
        await File('${root.path}/out/personal.txt').writeAsString('keep');
        final result = await clean(root);
        check(
          result.exitCode != 0 &&
              await File('${root.path}/out/personal.txt').exists(),
          'An empty child authorized deleting unrelated data',
        );
      },
    );
    stdout.writeln('$count clean tests passed');
  } finally {
    await temporary.delete(recursive: true);
  }
}
